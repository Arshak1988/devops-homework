/* =========================================================
   npm run build:worker  →  worker/worker.js
   Bundles the course data + worker/src/handler.js into ONE file
   that you can paste straight into the Cloudflare dashboard editor
   (or deploy with: npm run deploy:worker).
   ========================================================= */
const fs = require("fs");
const path = require("path");
const topics = require("../data/topics");
const toSummary = require("../data/summary");

const ROOT = path.join(__dirname, "..");
const handler = fs.readFileSync(path.join(ROOT, "worker", "src", "handler.js"), "utf8");

const out =
  `// GENERATED by scripts/build-worker.js — edit worker/src/handler.js or data/topics.js instead.\n` +
  `const TOPICS = ${JSON.stringify(topics)};\n` +
  `const SUMMARIES = ${JSON.stringify(topics.map(toSummary))};\n\n` +
  handler;

const file = path.join(ROOT, "worker", "worker.js");
fs.writeFileSync(file, out);
console.log(`✓ built worker/worker.js — ${(out.length / 1024).toFixed(0)} KB, ${topics.length} topics`);
console.log("  Paste it into the Cloudflare dashboard editor, or run: npm run deploy:worker");
